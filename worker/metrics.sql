CREATE TABLE IF NOT EXISTS events (id TEXT PRIMARY KEY, visitor TEXT NOT NULL, session TEXT NOT NULL, ts INTEGER NOT NULL, type TEXT NOT NULL, section TEXT NOT NULL, detail TEXT NOT NULL, source TEXT NOT NULL, campaign TEXT NOT NULL, duration INTEGER NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS events_ts ON events(ts);
CREATE INDEX IF NOT EXISTS events_type_ts ON events(type,ts);
CREATE TABLE IF NOT EXISTS purchases (id TEXT PRIMARY KEY, ts INTEGER NOT NULL, pack TEXT NOT NULL, stars INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS purchases_ts ON purchases(ts);
