  const FC_PROMPTS = ['Чего ты хочешь сильнее?', 'Чего ты боишься сильнее?', 'Каким тебя скорее видят люди?'];

  /** Претенденты: архетипы с одинаковым максимальным баллом (не больше трёх). Как в оригинале, лидер — тот, у кого больше баллов. */
  function contenders(answers) {
    const s = raw(answers); const r = ORDER.slice().sort((a, b) => s[b] - s[a]);
    return r.filter((k) => s[k] === s[r[0]]).slice(0, 3);
  }
  /** Уточняющие пары «что ближе» — только между архетипами с равным максимальным баллом. */
  function clarifyPlan(answers) {
    const c = contenders(answers); if (c.length < 2) return [];
    const pairs = []; for (let i = 0; i < c.length; i++) for (let j = i + 1; j < c.length; j++) pairs.push([c[i], c[j]]);
    const plan = [];
    pairs.forEach((pr, pi) => { for (let t = 0; t < 3; t++) { const type = (t + pi) % 3; plan.push({ type, prompt: FC_PROMPTS[type], opts: (t + pi) % 2 ? [pr[1], pr[0]] : pr }); } });
    return plan;
  }
  /** Следующий уточняющий вопрос или null. Если после плана равенство сохранилось — до 3 решающих вопросов. */
  function nextClarify(answers, picks) {
    picks = picks || [];
    const plan = clarifyPlan(answers);
    if (picks.length < plan.length) return plan[picks.length];
    const r = score(answers, picks);
    if (plan.length && r.tiedPicks && picks.length < plan.length + 3) { const type = picks.length % 3; return { type, prompt: FC_PROMPTS[type], opts: [r.ranked[0], r.ranked[1]], final: true }; }
    return null;
  }
  function raw(answers) { const s = {}; ORDER.forEach((k) => (s[k] = 0)); QUESTIONS.forEach((q, i) => { if (answers[i]) s[q.a] += answers[i]; }); return s; }

  /** Зоны как в оригинальном бланке: 6–11, 12–17, 18–23, 24–30. */
  const ZONES = [[24, 'active', 'Активная зона'], [18, 'developed', 'Развит'], [12, 'weak', 'Слабо выражен'], [6, 'dormant', 'Почти не проявлен']];
  const zoneOf = (v) => ZONES.find((z) => v >= z[0]);

  /** answers: 72 ответа 1–5; picks: выбор в уточняющем раунде (только при равенстве баллов). */
  function score(answers, picks) {
    const s = raw(answers), bonus = {}; ORDER.forEach((k) => (bonus[k] = 0));
    (picks || []).forEach((k) => { if (k) bonus[k] += 1; });
    // Порядок — по баллам; выбор в уточнении решает только между равными баллами
    const ranked = ORDER.slice().sort((a, b) => s[b] - s[a] || bonus[b] - bonus[a]);
    const top = s[ranked[0]], tied = ranked.filter((k) => s[k] === top);
    const tiedPicks = tied.length > 1 && bonus[ranked[0]] === bonus[ranked[1]] && s[ranked[1]] === top;
    const gap = top - s[ranked.find((k) => k !== ranked[0])];
    const clarity = tied.length > 1 ? 'tie' : gap >= 3 ? 'strong' : 'clear';
    const core = ranked.filter((k) => s[k] >= Math.max(24, top - 2));
    const active = ranked.filter((k) => s[k] >= 24);
    const vals = answers.filter(Boolean), mean = vals.reduce((a, b) => a + b, 0) / (vals.length || 1);
    const sd = Math.sqrt(vals.reduce((a, b) => a + (b - mean) ** 2, 0) / (vals.length || 1));
    const counts = [1, 2, 3, 4, 5].map((v) => vals.filter((x) => x === v).length);
    const flat = sd < 0.6 || Math.max(...counts) / (vals.length || 1) > 0.65;
    const drives = {}; for (const d in DRIVES) drives[d] = DRIVES[d].keys.reduce((a, k) => a + s[k], 0);
    const drive = Object.keys(drives).sort((a, b) => drives[b] - drives[a])[0];
    const why = QUESTIONS.map((q, i) => ({ q, v: answers[i] })).filter((x) => x.q.a === ranked[0]).sort((a, b) => b.v - a.v).slice(0, 3).filter((x) => x.v >= 4).map((x) => x.q.text);
    return { scores: s, bonus, ranked, top: ranked.slice(0, 3), low: ranked.slice(-2), core, active, gap, clarity, tied, tiedPicks, flat, drives, drive, why, max: MAX, clarified: (picks || []).length > 0 };
  }
  const SCALE = ['Совсем не про меня', 'Скорее нет', 'Иногда', 'Скорее да', 'Точно про меня'];
  return { A, ORDER, QUESTIONS, SCALE, score, contenders, clarifyPlan, nextClarify, ZONES, zoneOf, DRIVES, FC_PROMPTS, MAX, PER, VERSION };
